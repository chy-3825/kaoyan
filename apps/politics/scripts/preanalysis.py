def question_part(q: dict) -> str:
    text = re.sub(r"(?m)\s*20[0-9]{2}年全国硕士研究生招生考试政治第.*$", "", q.get("stem", ""))
    text = re.sub(r"[（(]\s*[）)]", "", text)
    parts = re.split(r"[。！？!?；;]", text)
    return next((part.strip(" \t\u3000，,：:（）()【】") for part in reversed(parts) if part.strip()), text.strip())


def is_negative(q: dict) -> bool:
    tail = question_part(q)
    return any(cue in tail for cue in NEGATIVE_CUES)


def focus_for(q: dict) -> str:
    text = q.get("stem", "")
    matches = [term for term in (*FOCUS_TERMS, *(marker for marker, _ in CORE_RATIONALES)) if term and term in text]
    if matches:
        return max(matches, key=len)
    tail = re.split(r"[，,；;]", q.get("stem", ""))[-1]
    tail = re.sub(r"[（(]\s*[）)]", "", tail).strip()
    pattern = re.compile(r"([^，,；;。！？?]{2,28}?)(?:是什么|是指|指的是|属于|不属于|不符合|不包括|不正确|错误的是|正确的是|实现的是|表现为|体现了|体现|说明|表明|在于|结果是)$")
    found = list(pattern.finditer(tail))
    if found:
        phrase = re.sub(r"\s+", "", found[-1].group(1))
        return phrase
    source_topic = str(q.get("sourceTopic", "")).strip()
    if source_topic:
        return source_topic
    clean = re.sub(r"[\s\u3000（）()【】《》“”‘’\"'，,。；;：:！？!?、]", "", tail)
    clean = re.sub(r"^(?:下列|以下|关于|对于|根据题干)?", "", clean)
    clean = re.sub(r"(?:的是|是|指|属于|不属于|不符合|不包括|不正确|错误)$", "", clean)
    return clean[-28:] or "题干与选项辨析"


def generate_preanalysis(q: dict) -> str:
    answer = "".join(c for c in str(q.get("answer", "")).upper() if c in "ABCD")
    options = q.get("options", {})
    selected = [f"{letter}“{options.get(letter, '')}”" for letter in answer]
    focus = focus_for(q)
    mode = "应选出的例外项" if is_negative(q) else "正确项"
    if len(answer) > 1:
        answer_basis = "；".join(selected)
    else:
        answer_basis = selected[0] if selected else "标准答案项"
    topic = q.get("topicTag", "考研政治")
    matches = [(len(marker), text) for marker, text in CORE_RATIONALES if marker and marker in q.get("stem", "")]
    rationale = max(matches, default=(0, ""), key=lambda item: item[0])[1]
    if rationale:
        q["explanationReviewStatus"] = "specific_rationale"
        detail = f"{rationale}因此，{mode}为{answer_basis}。"
    else:
        q["explanationReviewStatus"] = "answer_hint"
        detail = f"本题围绕“{focus}”设问，题库参考答案为{answer_basis}。现有资料没有匹配到本题专属的选项辨析，请结合教材核对题干限定和其余选项。"
    return (
        f"【考点】{topic}：{focus}。\n"
        f"{'【预解析】' if rationale else '【答案提示】'}{detail}"
    )


def annotate_records(rows: list[dict]) -> int:
    generated = 0
    for q in rows:
        if q.get("explanation", "").strip():
            q.setdefault("explanationKind", "source")
            q.setdefault("explanationReviewStatus", "source_provided")
            continue
        q["explanation"] = generate_preanalysis(q)
        q["explanationKind"] = "generated"
        generated += 1
    return generated
